import { railAt, type Rail, type Stage } from "./model";

function stage(
  number: number,
  title: string,
  path: readonly (readonly [number, number])[],
  gapIndexes: number[],
  extra: Rail[],
  speed: number,
): Stage {
  const data: Stage = {
    id: `journey-${number}`,
    number,
    title,
    chapter: Math.ceil(number / 4),
    theme: number <= 4 ? "meadow" : number <= 8 ? "river" : "sunset",
    path: path.map(([x, z]) => ({ x, z })),
    gaps: gapIndexes.map((pathIndex, i) => ({
      id: `journey-${number}-gap-${i + 1}`,
      pathIndex,
    })),
    pieces: [],
    speed,
  };
  data.pieces = [
    ...gapIndexes.map((index) => railAt(data, index)),
    ...extra,
  ].map((rail, i) => ({ id: `journey-${number}-piece-${i + 1}`, rail }));
  return data;
}

